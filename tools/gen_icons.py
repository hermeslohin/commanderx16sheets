out.append(f"    ubyte[{len(hi)}] ic_hi = [\n        {arr(hi)} ]")
out.append(f"    ubyte[{len(lo)}] ic_lo = [\n        {arr(lo)} ]")
out.append("}")
Path(__file__).resolve().parent.parent.joinpath("icons.p8").write_text("\n".join(out) + "\n")
